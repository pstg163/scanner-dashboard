function assertPin(pin: string): void {
  if (!/^\d{6}$/.test(pin) || pin === '000000') {
    throw new DashboardError('unauthorized', 401)
  }
}

function matches(alertRow: Alert, params: ListParams): boolean {
  if (params.county && (alertRow.county ?? '').toLowerCase() !== params.county.toLowerCase()) return false
  if (params.town && (alertRow.town ?? '').toLowerCase() !== params.town.toLowerCase()) return false
  if (params.category && (alertRow.category ?? '').toLowerCase() !== params.category.toLowerCase()) return false
  if (params.source_type && alertRow.source_type !== params.source_type) return false
  if (params.priority != null && alertRow.priority !== params.priority) return false
  if (params.since && alertRow.updated_at <= params.since) return false
  return true
}

export const mockApi: DashboardApi = {
  async list(pin, params = {}) {
    assertPin(pin)
    const limit = params.limit ?? 100
    const since = params.since ?? null
    let rows = ALERTS.filter((row) => matches(row, params))
    if (since) {
      rows.sort((a, b) => a.updated_at.localeCompare(b.updated_at) || a.id.localeCompare(b.id))
    } else {
      rows.sort((a, b) => b.event_time.localeCompare(a.event_time) || b.id.localeCompare(a.id))
    }
    rows = rows.slice(0, limit)
    const serverTime = new Date().toISOString()
    let pollAfter = serverTime
    const last = rows[rows.length - 1]
    if (since && rows.length === limit && last) pollAfter = last.updated_at
    const result: ListResult = {
      alerts: rows,
      count: rows.length,
      limit,
      since,
      serverTime,
      pollAfter,
    }
    return result
  },
  async get(pin, id) {
    assertPin(pin)
    const found = ALERTS.find((row) => row.id === id)
    if (!found) throw new DashboardError('not found', 404)
    return found
  },
  async clip(pin, id): Promise<ClipResult> {
    assertPin(pin)
    const found = ALERTS.find((row) => row.id === id)
    if (!found) throw new DashboardError('not found', 404)
    if (!found.clip_path) throw new DashboardError('no clip', 404)
    return { url: `${import.meta.env.BASE_URL}mock-clip.wav`, expiresIn: 3600, clipPath: found.clip_path }
  },
}
